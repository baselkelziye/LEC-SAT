#pragma once
// Shared Tseitin-encoding backend for cnf_gen.
//
// A "literal" here is a plain signed DIMACS int: +v means variable v true,
// -v means variable v false. Every wire in the source circuit resolves to
// exactly one such literal. Inversion (NOT) is *free*: it is just the sign
// on a literal, never its own CNF variable or clause. Only AND/OR/XOR gate
// outputs (and primary inputs) consume a fresh variable.

#include <cstdio>
#include <string>
#include <vector>

struct IoEntry {
    char direction;     // 'i' or 'o'
    std::string port;
    int bit;
    int lit;            // signed literal: value of this port bit
};

class CnfBuilder {
public:
    explicit CnfBuilder(std::string circuit_name) : name_(std::move(circuit_name)) {
        // Reserve variable 1 as a constant-true anchor, forced true by a
        // unit clause. Constant-false is simply its negation (-1).
        true_var_ = new_var();
        add_clause({true_var_});
    }

    int new_var() { return ++nvars_; }

    int true_lit() const { return true_var_; }
    int false_lit() const { return -true_var_; }

    void add_clause(std::vector<int> lits) { clauses_.push_back(std::move(lits)); }

    // z = x AND y. Returns the (positive) literal for z.
    int and2(int x, int y) {
        int z = new_var();
        add_clause({-z, x});
        add_clause({-z, y});
        add_clause({z, -x, -y});
        return z;
    }

    // z = x OR y. Returns the (positive) literal for z.
    int or2(int x, int y) {
        int z = new_var();
        add_clause({z, -x});
        add_clause({z, -y});
        add_clause({-z, x, y});
        return z;
    }

    // z = x XOR y. Returns the (positive) literal for z.
    int xor2(int x, int y) {
        int z = new_var();
        add_clause({-z, x, y});
        add_clause({-z, -x, -y});
        add_clause({z, x, -y});
        add_clause({z, -x, y});
        return z;
    }

    void add_io(char direction, const std::string& port, int bit, int lit) {
        io_.push_back({direction, port, bit, lit});
    }

    void write_cnf(const std::string& path, const std::string& provenance) const {
        FILE* f = std::fopen(path.c_str(), "w");
        std::fprintf(f, "c circuit %s\n", name_.c_str());
        std::fprintf(f, "c generated by cnf_gen (%s)\n", provenance.c_str());
        std::fprintf(f, "p cnf %d %zu\n", nvars_, clauses_.size());
        for (const auto& cl : clauses_) {
            for (int lit : cl) std::fprintf(f, "%d ", lit);
            std::fprintf(f, "0\n");
        }
        std::fclose(f);
    }

    void write_iomap(const std::string& path) const {
        FILE* f = std::fopen(path.c_str(), "w");
        std::fprintf(f, "c circuit %s\n", name_.c_str());
        for (const auto& e : io_) {
            int var = e.lit > 0 ? e.lit : -e.lit;
            char pol = e.lit > 0 ? '+' : '-';
            std::fprintf(f, "%c %s %d %d %c\n", e.direction, e.port.c_str(), e.bit, var, pol);
        }
        std::fclose(f);
    }

    int num_vars() const { return nvars_; }
    size_t num_clauses() const { return clauses_.size(); }

private:
    std::string name_;
    int nvars_ = 0;
    int true_var_ = 0;
    std::vector<std::vector<int>> clauses_;
    std::vector<IoEntry> io_;
};
